/* 21 тачка шаке — оно што детектор заправо шаље класификатору.
   Слика показује да модел не гледа пиксел руке него скелет од 21 координате,
   што је и разлог зашто препознавање ради без обзира на боју коже и рукав. */

// Тачке у јединичном простору (0–1), распоред отворене десне шаке.
const T = [
  [0.50, 0.95], // 0 зглоб
  [0.36, 0.82], [0.27, 0.71], [0.21, 0.61], [0.16, 0.52], // палац
  [0.40, 0.55], [0.38, 0.40], [0.37, 0.31], [0.36, 0.23], // кажипрст
  [0.50, 0.52], [0.50, 0.36], [0.50, 0.26], [0.50, 0.17], // средњи
  [0.60, 0.54], [0.62, 0.39], [0.63, 0.29], [0.64, 0.21], // домали
  [0.70, 0.59], [0.74, 0.47], [0.76, 0.39], [0.78, 0.32], // мали
]

const VEZE = [
  [0, 1], [1, 2], [2, 3], [3, 4],
  [0, 5], [5, 6], [6, 7], [7, 8],
  [0, 9], [9, 10], [10, 11], [11, 12],
  [0, 13], [13, 14], [14, 15], [15, 16],
  [0, 17], [17, 18], [18, 19], [19, 20],
  [5, 9], [9, 13], [13, 17], // длан
]

const PRSTI = [
  { naziv: 'палац', t: 4 },
  { naziv: 'кажипрст', t: 8 },
  { naziv: 'средњи', t: 12 },
  { naziv: 'домали', t: 16 },
  { naziv: 'мали', t: 20 },
]

export default function TackeShakeShema({ boja = 'currentColor' }) {
  const W = 300
  const H = 330
  const px = (i) => 30 + T[i][0] * (W - 60)
  const py = (i) => 16 + T[i][1] * (H - 46)

  return (
    <svg
      viewBox={`0 0 ${W} ${H}`}
      className="shema-svg shema-svg--usko"
      role="img"
      aria-label="Скелет шаке од 21 тачке: зглоб, четири зглоба по прсту и врхови палца, кажипрста, средњег, домалог и малог прста."
    >
      {VEZE.map(([a, b], i) => (
        <line key={i} x1={px(a)} y1={py(a)} x2={px(b)} y2={py(b)} className="shema-veza" />
      ))}
      {T.map((_, i) => (
        <circle key={i} cx={px(i)} cy={py(i)} r={i === 0 ? 7 : 4.5}
          fill={boja} opacity={i === 0 ? 0.95 : 0.75} />
      ))}
      {PRSTI.map((p) => (
        <text key={p.naziv} x={px(p.t)} y={py(p.t) - 12} className="shema-t-mini" textAnchor="middle">
          {p.naziv}
        </text>
      ))}
      <text x={px(0) + 14} y={py(0) + 4} className="shema-t-port">зглоб · тачка 0</text>
    </svg>
  )
}
