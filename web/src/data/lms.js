/* Тачан одговор не сме да буде увек на истом месту: опције се ротирају за
   (редни број питања + редни број лекције) места. Редослед је стално исти,
   па нема случајности између рендера. */
const razbaci = (pitanja = [], lekcijaIdx) =>
  pitanja.map((p, i) => {
    const n = p.opcije.length
    const pomak = (i + lekcijaIdx) % n
    return {
      ...p,
      opcije: p.opcije.map((_, k) => p.opcije[(k + n - pomak) % n]),
      tacno: (p.tacno + pomak) % n,
    }
  })

export const lekcije = lekcijeBaza.map((l, idx) => ({ ...l, kviz: razbaci(kviz[l.slug], idx) }))

