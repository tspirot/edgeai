    def pozovi_llm(self, poruke: list[dict], persona: str = "stedisa") -> str | None:
        """Позива стварни LLM модел (Groq, Gemini, OpenRouter, OpenAI или Ollama)."""
        provider = (self.ai_provider or "offline").lower().strip()
        system_prompt = self._generisi_sistemski_prompt(persona)

        # 1. GOOGLE GEMINI
        if provider == "gemini" and self.api_key:
            model = self.llm_model or "gemini-2.0-flash"
            url = f"https://generativelanguage.googleapis.com/v1beta/models/{model}:generateContent?key={self.api_key}"
            contents = []
            for p in poruke[-6:]:
                role = "user" if p.get("role") == "user" else "model"
                contents.append({"role": role, "parts": [{"text": p.get("content", "")}]})
            payload = {
                "system_instruction": {"parts": [{"text": system_prompt}]},
                "contents": contents,
                "generationConfig": {"temperature": 0.75, "maxOutputTokens": 1024}
            }
            try:
                req = urllib.request.Request(url, data=json.dumps(payload).encode("utf-8"), headers={"Content-Type": "application/json"})
                with urllib.request.urlopen(req, timeout=18) as resp:
                    data = json.loads(resp.read().decode("utf-8"))
                    return data["candidates"][0]["content"]["parts"][0]["text"].strip()
            except Exception as e:
                print(f"[Gemini Error]: {e}")
                return None

        # 2. GROQ (OpenAI-compatible)
        if provider == "groq" and self.api_key:
            model = self.llm_model or "llama-3.3-70b-versatile"
            url = "https://api.groq.com/openai/v1/chat/completions"
            return self._pozovi_openai_api(url, self.api_key, model, system_prompt, poruke)

        # 3. OPENROUTER (OpenAI-compatible)
        if provider == "openrouter" and self.api_key:
            model = self.llm_model or "meta-llama/llama-3.3-70b-instruct:free"
            url = "https://openrouter.ai/api/v1/chat/completions"
            return self._pozovi_openai_api(url, self.api_key, model, system_prompt, poruke)

        # 4. OPENAI (OpenAI-compatible)
        if provider == "openai" and self.api_key:
            model = self.llm_model or "gpt-4o-mini"
            url = "https://api.openai.com/v1/chat/completions"
            return self._pozovi_openai_api(url, self.api_key, model, system_prompt, poruke)

        # 5. OLLAMA (Lokalni LLM)
        if provider in ["ollama", "local"]:
            model = self.llm_model or self.ollama_model or "llama3"
            url = f"{self.ollama_url}/api/chat"
            msgs = [{"role": "system", "content": system_prompt}]
            for p in poruke[-6:]:
                msgs.append({"role": p.get("role", "user"), "content": p.get("content", "")})
            try:
                payload = {"model": model, "messages": msgs, "stream": False, "options": {"temperature": 0.75}}
                req = urllib.request.Request(url, data=json.dumps(payload).encode("utf-8"), headers={"Content-Type": "application/json"})
                with urllib.request.urlopen(req, timeout=25) as resp:
                    data = json.loads(resp.read().decode("utf-8"))
                    return data.get("message", {}).get("content", "").strip()
            except Exception as e:
                print(f"[Ollama Error]: {e}")
                return None

        return None

    def _pozovi_openai_api(self, url: str, api_key: str, model: str, system_prompt: str, poruke: list[dict]) -> str | None:
        """Помоћна функција за OpenAI-компатибилне сервере (Groq, OpenRouter, OpenAI)."""
        msgs = [{"role": "system", "content": system_prompt}]
        for p in poruke[-6:]:
            msgs.append({"role": p.get("role", "user"), "content": p.get("content", "")})
        payload = {
            "model": model,
            "messages": msgs,
            "temperature": 0.75,
            "max_tokens": 1200
        }
        try:
            req = urllib.request.Request(
                url,
                data=json.dumps(payload).encode("utf-8"),
                headers={
                    "Content-Type": "application/json",
                    "Authorization": f"Bearer {api_key}"
                }
            )
            with urllib.request.urlopen(req, timeout=18) as resp:
                data = json.loads(resp.read().decode("utf-8"))
                return data["choices"][0]["message"]["content"].strip()
        except Exception as e:
            print(f"[LLM API Error]: {e}")
            return None

