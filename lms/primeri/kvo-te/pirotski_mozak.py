    def sacuvaj_konfiguraciju(self, provider: str, api_key: str, model: str) -> bool:
        """Чува нова подешавања у config.yaml."""
        putanja = Path(__file__).resolve().parent / "config.yaml"
        try:
            cfg = {}
            if putanja.exists():
                with open(putanja, "r", encoding="utf-8") as f:
                    cfg = yaml.safe_load(f) or {}
            if "ai" not in cfg:
                cfg["ai"] = {}
            cfg["ai"]["provider"] = provider
            cfg["ai"]["api_key"] = api_key
            cfg["ai"]["model"] = model
            with open(putanja, "w", encoding="utf-8") as f:
                yaml.safe_dump(cfg, f, allow_unicode=True, sort_keys=False)
            self.ai_provider = provider
            self.api_key = api_key
            self.llm_model = model
            return True
        except Exception:
            return False

    def prepoznaj_nameru(self, tekst: str) -> str:
        """Одреди тему/намеру питања на основу кључних речи."""
        cist = tekst.lower().strip()

        # Провера за речник: "шта значи...", "кво значи...", "како се каже...", "шта је..."
        okidaci_recnik = [
            "шта значи", "кво значи", "значење", "sta znaci", "objasni", "објасни",
            "речник", "recnik", "како се каже", "kako se kaze", "шта је", "sta je",
            "кво је", "kvo je", "преведи", "prevedi"
        ]
        if any(w in cist for w in okidaci_recnik):
            return "recnik"

        for intent, reci in INTENT_KEYWORDS.items():
            for r in reci:
                if r in cist:
                    return intent

        return "filozofija_i_zivot"

    def odgovori_iz_recnika(self, tekst: str) -> str:
        """Ако је корисник питао за одређену реч из пиротског говора."""
        cist = tekst.lower()

        # 1. Прво претражи научни модел из recnik.pdf (2700+ одредница)
        reci_u_upitu = re.findall(r'[^\s\d\,\.\;\:\!\?\"\(\)\[\]]+', cist)
        # Уклони stop-reči
        stop_reci = {"шта", "значи", "кво", "sta", "znaci", "како", "се", "каже", "реч", "rec", "речник", "штаје", "staje", "је", "јесте"}
        kandidati = [r for r in reci_u_upitu if r not in stop_reci and len(r) >= 2]

        pronadjeni_iz_modela = []
        for k in kandidati:
            p_rez = self.model.nadji_pirotsku_rec(k)
            for odr in p_rez:
                fmt = self.model.formatiraj_odgovor(odr)
                if fmt not in pronadjeni_iz_modela:
                    pronadjeni_iz_modela.append(fmt)
            if len(pronadjeni_iz_modela) >= 3:
                break

        # Ако нема као пиротска реч, тражи као српски појам (обратно)
        if not pronadjeni_iz_modela:
            for k in kandidati:
                s_rez = self.model.nadji_srpski_pojam(k)
                for odr in s_rez:
                    fmt = self.model.formatiraj_odgovor(odr)
                    if fmt not in pronadjeni_iz_modela:
                        pronadjeni_iz_modela.append(fmt)
                if len(pronadjeni_iz_modela) >= 3:
                    break

        if pronadjeni_iz_modela:
            return "Слушај вамо из научног пиротског речника (САНУ):\n" + "\n".join(pronadjeni_iz_modela[:2])

        # 2. Fallback на кратку уграђену базу
        pronadjene = []
        for rec, objasnjenje in self.recnik.items():
            if rec in cist:
                pronadjene.append(f"• '{rec.upper()}': {objasnjenje}")

        if pronadjene:
            return "Слушај вамо да научиш пиротски:\n" + "\n".join(pronadjene)
        
        # 3. Насумична одредница из модела као предлог
        sl = self.model.slucajna_odrednica()
        if sl:
            return f"Еее комшија, туј реч нисам чуја у наш сокак! Ал' еве једна убава пиротска реч за тебе:\n{self.model.formatiraj_odgovor(sl)}"

        primeri = ", ".join(list(self.recnik.keys())[:5])
        return f"Еее комшија, туј реч нисам чуја у наш сокак! Питај ме за пиротске речи, нпр: {primeri}..."

